import fs from "node:fs";
import path from "node:path";
import { Config } from "@remotion/cli/config";
import { enableTailwind } from "@remotion/tailwind-v4";

Config.setVideoImageFormat("jpeg");
Config.setOverwriteOutput(true);

// Folders inside projects/ that never affect the bundle. The registry watches all of projects/,
// so without this, rendering with Remotion Studio open would trigger rebuild after rebuild.
const notBundled = /[\\/]projects[\\/][^\\/]+[\\/](?:renders|qa|output|subtitles|locales|scenes[\\/]manim)[\\/]/;

// Scene code lives outside this folder (projects/<slug>/scenes/remotion/), so webpack needs
// this folder's node_modules and the `@studio` alias (mirrored in tsconfig.json `paths`).
Config.overrideWebpackConfig((currentConfiguration) => {
  const config = enableTailwind(currentConfiguration);
  const ignored = config.watchOptions?.ignored;
  return {
    ...config,
    watchOptions: {
      ...config.watchOptions,
      ignored: ignored instanceof RegExp
        ? new RegExp(`(?:${ignored.source})|(?:${notBundled.source})`, ignored.flags)
        : ignored,
    },
    resolve: {
      ...config.resolve,
      alias: { ...config.resolve?.alias, "@studio": path.join(process.cwd(), "src", "studio") },
      modules: [...(config.resolve?.modules ?? ["node_modules"]), path.join(process.cwd(), "node_modules")],
    },
  };
});

// Tailwind skips git-ignored folders when it scans for class names, and videos are git-ignored
// unless published. Naming each video's scene folder in its own @source makes Tailwind scan it
// anyway. Regenerated whenever the Remotion CLI starts; the file itself is git-ignored.
const projectsDir = path.join(process.cwd(), "..", "projects");
const slugs = fs.existsSync(projectsDir)
  ? fs.readdirSync(projectsDir).filter((slug) => fs.existsSync(path.join(projectsDir, slug, "scenes", "remotion")))
  : [];
const sources = [
  "/* Generated by remotion.config.ts: one @source per video. Do not edit. */",
  ...slugs.sort().map((slug) => `@source "../../projects/${slug}/scenes/remotion";`),
].join("\n") + "\n";
const sourcesFile = path.join(process.cwd(), "src", "sources.generated.css");
if (!fs.existsSync(sourcesFile) || fs.readFileSync(sourcesFile, "utf8") !== sources) {
  fs.writeFileSync(sourcesFile, sources);
}
